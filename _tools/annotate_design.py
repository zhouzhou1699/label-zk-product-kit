"""
把真实界面截图做成「设计走查标注图」：编号热点框 + 右侧问题/建议面板。
输入：_zk/shots2/vp-*.png（1600×1000 视口截图，标注坐标以此为准）
输出：05-assets/annotated/*.png
用法：python annotate_design.py
"""
import os
from PIL import Image, ImageDraw, ImageFont

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC_DIRS = [os.path.join(BASE, "05-assets", "screens"), os.path.join(BASE, "_src")]
OUT = os.path.join(BASE, "05-assets", "annotated")
os.makedirs(OUT, exist_ok=True)

FONT_B = "C:/Windows/Fonts/msyhbd.ttc"
FONT_R = "C:/Windows/Fonts/msyh.ttc"

INK, SUB = (22, 35, 58), (90, 107, 130)
DANGER, WARN, OK, INFO = (229, 84, 75), (232, 161, 58), (31, 169, 113), (43, 145, 248)
PANEL, LINE = (247, 250, 255), (227, 236, 247)


def font(path, size):
    return ImageFont.truetype(path, size)


def wrap(draw, text, fnt, max_w):
    lines, cur = [], ""
    for ch in text:
        if ch == "\n":
            lines.append(cur); cur = ""; continue
        if draw.textlength(cur + ch, font=fnt) > max_w:
            lines.append(cur); cur = ch
        else:
            cur += ch
    if cur:
        lines.append(cur)
    return lines


def find(name):
    for d in SRC_DIRS:
        p = os.path.join(d, name)
        if os.path.exists(p):
            return p
    raise FileNotFoundError(name)


def annotate(src, dst, title, subtitle, marks, panel_w=440):
    """marks: [(x, y, w, h, kind, heading, body)] kind: danger|warn|ok|info"""
    img = Image.open(find(src)).convert("RGB")
    W, H = img.size
    total_w, total_h = W + panel_w, max(H, 820)
    canvas = Image.new("RGB", (total_w, total_h), "white")
    canvas.paste(img, (0, 0))

    colors = {"danger": DANGER, "warn": WARN, "ok": OK, "info": INFO}
    ov = Image.new("RGBA", canvas.size, (0, 0, 0, 0))
    od = ImageDraw.Draw(ov)

    for i, m in enumerate(marks, 1):
        x, y, w, h, kind = m[0], m[1], m[2], m[3], m[4]
        c = colors[kind]
        od.rounded_rectangle([x, y, x + w, y + h], radius=6, outline=c + (255,), width=2)
        cx, cy = x + 2, y - 1
        r = 13
        od.ellipse([cx - r, cy - r, cx + r, cy + r], fill=c + (255,), outline=(255, 255, 255, 255), width=2)
        od.text((cx, cy), str(i), font=font(FONT_B, 14), fill=(255, 255, 255, 255), anchor="mm")

    canvas = Image.alpha_composite(canvas.convert("RGBA"), ov).convert("RGB")
    d = ImageDraw.Draw(canvas)

    d.rectangle([W, 0, total_w, total_h], fill=PANEL)
    d.line([W, 0, W, total_h], fill=LINE, width=1)

    y = 26
    d.text((W + 24, y), title, font=font(FONT_B, 18), fill=INK); y += 28
    for ln in wrap(d, subtitle, font(FONT_R, 12), panel_w - 48):
        d.text((W + 24, y), ln, font=font(FONT_R, 12), fill=SUB); y += 18
    y += 10
    d.line([W + 24, y, total_w - 24, y], fill=LINE, width=1); y += 16

    for i, m in enumerate(marks, 1):
        kind, head, body = m[4], m[5], m[6]
        c = colors[kind]
        d.ellipse([W + 24, y + 1, W + 44, y + 21], fill=c)
        d.text((W + 34, y + 11), str(i), font=font(FONT_B, 12), fill="white", anchor="mm")
        for ln in wrap(d, head, font(FONT_B, 13), panel_w - 78)[:2]:
            d.text((W + 52, y), ln, font=font(FONT_B, 13), fill=INK); y += 19
        for ln in wrap(d, body, font(FONT_R, 11), panel_w - 78):
            d.text((W + 52, y), ln, font=font(FONT_R, 11), fill=SUB); y += 17
        y += 13
        if y > total_h - 70:
            break

    d.text((W + 24, total_h - 26), "Label ZK · 设计走查标注图 · 2026-11",
           font=font(FONT_R, 10), fill=(164, 159, 149))
    canvas.save(os.path.join(OUT, dst))
    print("saved", dst, canvas.size)


